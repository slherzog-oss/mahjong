export function t(key, vars = {}) {
  let s = key.split('.').reduce((o, k) => (o == null ? undefined : o[k]), de);
  if (s === undefined) return key;
  if (typeof s !== 'string') return s;
  for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}
